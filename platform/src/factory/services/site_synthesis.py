"""The synthesis product: the recorded, model-written pages about the corpus (plan site-hub,
step 4).

Each page is shown as recorded (never regenerated by a build), labelled model-written, with who
wrote it, when, the mechanical check it passed, its flags, and a warning when the rows it was
written from have changed. Citations `[[works/<slug>]]` link to the paper in the explorer.
"""

from __future__ import annotations

import html
import re
from pathlib import Path
from typing import Any

from factory.services.context import Project
from factory.services.pages import list_pages, read_page
from factory.services.site_corpus import corpus_payload
from factory.services.site_widgets import REPORT_CSS, esc, note

_LINK = re.compile(r"\[\[works/([^\]|]+)(?:\|[^\]]*)?\]\]")


def file_name(scope: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", scope.lower()).strip("-")


def markdown_to_html(body: str, titles: dict[str, str]) -> str:
    """A small Markdown renderer: headings, paragraphs, lists, bold, and work citations."""

    def cite(m: re.Match[str]) -> str:
        slug = m.group(1)
        label = html.escape((titles.get(slug) or slug)[:34])
        return (
            f"<a class=cite href='../explorer/index.html#open={slug}' title='{label}'>[{label}]</a>"
        )

    def inline(text: str) -> str:
        out = html.escape(text, quote=False)
        out = _LINK.sub(cite, out)
        return re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", out)

    parts: list[str] = []
    items: list[str] = []

    def flush() -> None:
        if items:
            parts.append("<ul>" + "".join(f"<li>{i}</li>" for i in items) + "</ul>")
            items.clear()

    for line in body.splitlines():
        s = line.strip()
        if not s:
            flush()
        elif s.startswith("#"):
            flush()
            level = min(len(s) - len(s.lstrip("#")), 3)
            parts.append(f"<h{level}>{inline(s.lstrip('# '))}</h{level}>")
        elif re.match(r"^[-*]\s+", s):
            items.append(inline(re.sub(r"^[-*]\s+", "", s)))
        else:
            flush()
            parts.append(f"<p>{inline(s)}</p>")
    flush()
    return "".join(parts)


_CSS = (
    REPORT_CSS + ".cite{font-size:11px;color:var(--blue);margin:0 1px}.cite:hover{color:var(--ac)}"
    ".badge{display:inline-block;font-size:11px;border:1px solid var(--mut);border-radius:10px;"
    "padding:0 8px;margin-right:6px;color:var(--dim)}.badge.warn{color:var(--amber)}"
    ".page h1{font-size:22px}.page h2{margin-top:22px}.page p,.page li{max-width:80ch}"
    ".flag{color:var(--amber);font-size:13px;margin:2px 0}a.row{display:block;padding:12px 14px;"
    "border:1px solid var(--mut);border-radius:8px;background:var(--lt);margin:8px 0;"
    "color:var(--fg)}a.row:hover{background:var(--sel)}.sub{color:var(--dim);font-size:13px}"
)


def _scope_table(payload: dict[str, Any], infos: list[Any]) -> str:
    """Every scope a page can be written for, with its works and whether a page exists."""
    from factory.services.pages import subset

    have = {i.scope: i for i in infos}
    values: dict[str, set[str]] = {"technique": set(), "stage": set(), "field": set()}
    for w in payload["works"]:
        for f, key in (
            ("technique_primary", "technique"),
            ("technique_secondary", "technique"),
            ("field_primary", "field"),
        ):
            v = (w["cls"].get(f) or {}).get("v")
            if v:
                values[key].add(v)
        for s in w["stages"]:
            values["stage"].add(s["stage"])
    scopes = ["overview"] + [
        f"{k}={v}"
        for k in ("technique", "stage", "field")
        for v in sorted(values[k])
        if re.match(r"^[a-z0-9][a-z0-9-]*$", v)
    ]
    rows = ""
    for scope in scopes:
        try:
            n = len(subset(payload, scope)[0])
        except Exception:
            continue
        info = have.get(scope)
        if info is None:
            state = "<span class=dim>no page yet</span>"
        else:
            state = f"<a href='{file_name(scope)}.html'>read</a>" + (
                " · <span class='badge warn'>stale</span>" if info.stale else ""
            )
        kind, _, val = scope.partition("=")
        href = (
            f"../explorer/index.html#view=list&f={kind}:{val}" if val else "../explorer/index.html"
        )
        rows += (
            f"<tr class=clk onclick=\"location.href='{href}'\"><td><a href='{href}'>{esc(scope)}</a></td>"
            f"<td class=n><a href='{href}'>{n}</a></td><td>{state}</td></tr>"
        )
    how = (
        "<p class=dim>To write or revise a page, open a Claude Code session on this project and ask it to "
        "use the <b>rf-synthesize</b> skill for a scope, for example: <code>Write the synthesis page for "
        "technique=memory-skills with the rf-synthesize skill</code>. The skill reads the brief "
        "(statistics and quoted rows), writes the page and records it; the platform checks it. A page "
        "marked stale was written before the rows changed: ask for a revision.</p>"
    )
    return (
        "<h2>Scopes a page can be written for</h2>"
        "<p class=dim>Each scope is a technique, lifecycle stage or field of science, or the whole corpus. "
        "The number is how many papers the page would cover.</p>"
        f"<table><tr><th>scope</th><th>works</th><th>page</th></tr>{rows}</table>{how}"
    )


def build_synthesis(project: Project, out: Path) -> None:
    from factory.services.site import page

    payload = corpus_payload(project)
    titles: dict[str, str] = {w["slug"]: w["title"] for w in payload["works"]}
    infos = list_pages(project)
    cards = ""
    for info in infos:
        data: dict[str, Any] = read_page(project, info.page_id)
        who = data.get("model") or data.get("actor_kind") or ""
        check = data["check"]
        badges = "<span class=badge>model-written</span>"
        if info.stale:
            badges += "<span class='badge warn'>stale: the rows changed since</span>"
        if info.flags:
            badges += f"<span class='badge warn'>{info.flags} flag(s)</span>"
        flags = "".join(f"<div class=flag>Flag: {esc(f['sentence'])}</div>" for f in check["flags"])
        summary = (
            f"Checked mechanically when recorded: {check['cited_sentences']} cited sentences, "
            f"{check['quotes_checked']} quotations verified verbatim, {check['numbers_checked']} "
            "numbers checked against the computed statistics."
        )
        head = (
            f"<p class=sub>{badges} {esc(info.scope)} · {esc(who)} · {esc(info.recorded_at[:16])} "
            f"· {info.words} words · {esc(info.page_id)}</p>{note(summary)}{flags}"
        )
        name = file_name(info.scope)
        (out / f"{name}.html").write_text(
            page(
                info.title,
                f"<div class=page><p class=sub><a href='index.html'>← all pages</a></p>{head}"
                f"{markdown_to_html(data['body'], titles)}</div>",
                _CSS,
            ),
            encoding="utf-8",
        )
        cards += (
            f"<a class=row href='{name}.html'><b>{esc(info.title)}</b><div class=sub>{badges} "
            f"{esc(info.scope)} · {esc(who)} · {info.words} words</div></a>"
        )
    scopes = _scope_table(payload, infos)
    intro = note(
        "Pages written by a model from the recorded, quoted rows. They are interpretations, never "
        "evidence: each was checked mechanically when recorded (cited works exist, quotations are "
        "verbatim, numbers come from the computed statistics) and is marked stale when the rows "
        "change. To add or revise a page, run a Claude session with the rf-synthesize skill."
    )
    empty = "" if infos else note("No page is recorded yet.")
    (out / "index.html").write_text(
        page(
            "Synthesis pages",
            f"<h1>Synthesis pages</h1>{intro}{empty}{cards}{scopes}",
            _CSS,
        ),
        encoding="utf-8",
    )
