def t_quantile(level: Level, df: int) -> Decimal:
    """The two-sided quantile for `level` at `df` degrees of freedom (see module invariants)."""
    if df < 1:
        raise ValueError("degrees of freedom start at 1")
    if level not in _TABLE:
        raise ValueError(f"unknown confidence level {level!r}")
    index = max(i for i, d in enumerate(_DFS) if d <= df)
    return Decimal(_TABLE[level][index])
